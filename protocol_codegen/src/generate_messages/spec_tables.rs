//! Emits data-only schema tables for the `proto-kafka-spec` crate.
//! This module MUST NOT emit encode/decode logic: field descriptors only.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use failure::{bail, format_err, Error};
use inflector::cases::screamingsnakecase::to_screaming_snake_case;

use super::spec::{FieldSpec, PrimitiveType, Spec, SpecType, TypeSpec, VersionSpec};

pub fn emit(specs: &[Spec]) -> Result<String, Error> {
    let mut out = String::new();
    writeln!(out, "// WARNING: generated by protocol_codegen (generate_messages/spec_tables.rs). Do not edit.")?;
    writeln!(
        out,
        "// Data only: Kafka 4.1.0 message schemas as static tables."
    )?;
    writeln!(out, "#![allow(clippy::all)]")?;
    writeln!(out, "use crate::schema::*;")?;
    let mut all = Vec::new();
    for spec in specs {
        let msg = to_screaming_snake_case(&spec.name);
        let mut structs: BTreeMap<String, Vec<FieldSpec>> = BTreeMap::new();
        for cs in &spec.common_structs {
            structs.insert(cs.name.clone(), cs.fields.clone());
        }
        collect_inline(&spec.fields, &mut structs)?;
        if structs.keys().any(|k| to_screaming_snake_case(k) == "ROOT") {
            bail!(
                "{}: struct named Root collides with the root ident",
                spec.name
            );
        }
        writeln!(out)?;
        for (name, fields) in &structs {
            emit_struct(&mut out, &msg, &to_screaming_snake_case(name), name, fields)?;
        }
        emit_struct(&mut out, &msg, "ROOT", &spec.name, &spec.fields)?;
        let api_key = spec
            .api_key
            .map_or("None".to_string(), |k| format!("Some({k})"));
        let kind = match spec.type_ {
            SpecType::Request => "Request",
            SpecType::Response => "Response",
            SpecType::Header => "Header",
            SpecType::Data => "Data",
        };
        writeln!(
            out,
            "pub static {msg}: MessageSchema = MessageSchema {{ name: {:?}, api_key: {api_key}, kind: Kind::{kind}, valid: {}, flexible: {}, root: &{msg}__ROOT }};",
            spec.name,
            versions(spec.valid_versions),
            versions(spec.flexible_versions),
        )?;
        all.push(format!("&{msg}"));
    }
    writeln!(out)?;
    writeln!(
        out,
        "pub static ALL: &[&MessageSchema] = &[{}];",
        all.join(", ")
    )?;
    Ok(out)
}

fn struct_name(t: &TypeSpec) -> Option<&str> {
    match t {
        TypeSpec::Struct(n) => Some(n),
        TypeSpec::Array(inner) => match inner.as_ref() {
            TypeSpec::Struct(n) => Some(n),
            _ => None,
        },
        TypeSpec::Primitive(_) => None,
    }
}

fn collect_inline(
    fields: &[FieldSpec],
    out: &mut BTreeMap<String, Vec<FieldSpec>>,
) -> Result<(), Error> {
    for f in fields {
        if !f.fields.is_empty() {
            let Some(name) = struct_name(&f.type_) else {
                bail!(
                    "field {} has nested fields but is not a struct type",
                    f.name
                );
            };
            if out.insert(name.to_string(), f.fields.clone()).is_some() {
                bail!("duplicate struct name {name}");
            }
            collect_inline(&f.fields, out)?;
        }
    }
    Ok(())
}

fn versions(v: VersionSpec) -> String {
    match v {
        VersionSpec::None => "Versions::NONE".into(),
        VersionSpec::Exact(a) => format!("Versions::range({a}, {a})"),
        VersionSpec::Since(a) => format!("Versions::since({a})"),
        VersionSpec::Range(a, b) => format!("Versions::range({a}, {b})"),
    }
}

fn field_type(msg: &str, t: &TypeSpec) -> Result<String, Error> {
    Ok(match t {
        TypeSpec::Primitive(p) => format!("FieldType::Prim(Prim::{p:?})"),
        TypeSpec::Struct(n) => format!("FieldType::Struct(&{msg}__{})", to_screaming_snake_case(n)),
        TypeSpec::Array(inner) => match inner.as_ref() {
            TypeSpec::Primitive(p) => format!("FieldType::PrimArray(Prim::{p:?})"),
            TypeSpec::Struct(n) => format!(
                "FieldType::StructArray(&{msg}__{})",
                to_screaming_snake_case(n)
            ),
            TypeSpec::Array(_) => return Err(format_err!("arrays of arrays are not supported")),
        },
    })
}

fn parse_int(s: &str) -> Result<i64, Error> {
    Ok(match s.strip_prefix("0x") {
        Some(hex) => i64::from_str_radix(hex, 16)?,
        None => s.parse()?,
    })
}

fn default_expr(f: &FieldSpec) -> Result<String, Error> {
    use serde_json::Value as J;
    let prim = match &f.type_ {
        TypeSpec::Primitive(p) => Some(*p),
        _ => None,
    };
    Ok(match &f.default {
        None => "DefaultVal::Type".into(),
        Some(J::String(s)) if s == "null" => "DefaultVal::Null".into(),
        Some(J::Bool(b)) => format!("DefaultVal::Bool({b})"),
        Some(J::Number(n)) => format!("DefaultVal::Int({})", n.as_i64().expect("integer default")),
        Some(J::String(s)) => match prim {
            Some(PrimitiveType::Bool) => format!("DefaultVal::Bool({})", s.parse::<bool>()?),
            Some(
                PrimitiveType::Int8
                | PrimitiveType::Int16
                | PrimitiveType::Uint16
                | PrimitiveType::Int32
                | PrimitiveType::Int64,
            ) => {
                format!("DefaultVal::Int({})", parse_int(s)?)
            }
            Some(PrimitiveType::String) => format!("DefaultVal::Str({s:?})"),
            _ if s.is_empty() => "DefaultVal::Type".into(),
            _ => {
                return Err(format_err!(
                    "field {}: unsupported default {s:?} for type {}",
                    f.name,
                    f.type_
                ))
            }
        },
        Some(other) => return Err(format_err!("field {}: unsupported default {other}", f.name)),
    })
}

fn emit_struct(
    out: &mut String,
    msg: &str,
    ident: &str,
    name: &str,
    fields: &[FieldSpec],
) -> Result<(), Error> {
    writeln!(
        out,
        "pub static {msg}__{ident}: StructSchema = StructSchema {{ name: {name:?}, fields: &["
    )?;
    for f in fields {
        // Java reads a *tagged* nullable struct's presence as `readUnsignedVarint() <= 0`
        // (MessageDataGenerator.generateStructReader, tagged=true), not the 1-byte marker the
        // spec interpreter implements for untagged nullable structs. No Kafka 4.1.0 schema has
        // one, so refuse to emit it rather than silently produce a wrong table.
        if matches!(f.type_, TypeSpec::Struct(_))
            && f.tag.is_some()
            && f.nullable_versions != VersionSpec::None
        {
            bail!(
                "{name}.{}: tagged nullable struct fields are not supported by the spec \
                 interpreter (Java reads a varint presence marker; see docs/FINDINGS.md)",
                f.name
            );
        }
        let tag = f.tag.map_or("None".to_string(), |t| format!("Some({t})"));
        let flexible = f
            .flexible_versions
            .map_or("None".to_string(), |v| format!("Some({})", versions(v)));
        writeln!(
            out,
            "    FieldDesc {{ name: {:?}, ty: {}, versions: {}, nullable: {}, tag: {tag}, tagged: {}, flexible: {flexible}, default: {}, ignorable: {} }},",
            f.name,
            field_type(msg, &f.type_)?,
            versions(f.versions),
            versions(f.nullable_versions),
            versions(f.tagged_versions),
            default_expr(f)?,
            f.ignorable,
        )?;
    }
    writeln!(out, "] }};")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generate_messages::spec::Spec;

    fn spec(json: &str) -> Spec {
        serde_json::from_str(json).unwrap()
    }

    #[test]
    fn emits_fields_versions_defaults_and_structs() {
        let s = spec(
            r#"{
          "apiKey": 10, "type": "request", "name": "FindCoordinatorRequest",
          "validVersions": "0-6", "flexibleVersions": "3+",
          "fields": [
            { "name": "Key", "type": "string", "versions": "0-3" },
            { "name": "KeyType", "type": "int8", "versions": "1+", "default": "0" },
            { "name": "Max", "type": "int32", "versions": "0+", "default": "0x7fffffff" },
            { "name": "Coords", "type": "[]Coord", "versions": "4+", "nullableVersions": "5+", "default": "null",
              "fields": [ { "name": "Id", "type": "int32", "versions": "4+", "taggedVersions": "4+", "tag": 0, "default": -1 } ] },
            { "name": "ClientId", "type": "string", "versions": "1+", "nullableVersions": "1+", "flexibleVersions": "none" }
          ]
        }"#,
        );
        let out = emit(&[s]).unwrap();
        assert!(
            out.contains("pub static FIND_COORDINATOR_REQUEST: MessageSchema = MessageSchema {"),
            "{out}"
        );
        assert!(out.contains("api_key: Some(10), kind: Kind::Request, valid: Versions::range(0, 6), flexible: Versions::since(3)"), "{out}");
        assert!(out.contains(r#"FieldDesc { name: "Key", ty: FieldType::Prim(Prim::String), versions: Versions::range(0, 3), nullable: Versions::NONE, tag: None, tagged: Versions::NONE, flexible: None, default: DefaultVal::Type, ignorable: false }"#), "{out}");
        assert!(
            out.contains(
                r#"name: "KeyType", ty: FieldType::Prim(Prim::Int8), versions: Versions::since(1)"#
            ),
            "{out}"
        );
        assert!(out.contains("default: DefaultVal::Int(0)"), "{out}");
        assert!(
            out.contains("default: DefaultVal::Int(2147483647)"),
            "{out}"
        );
        assert!(
            out.contains("ty: FieldType::StructArray(&FIND_COORDINATOR_REQUEST__COORD)"),
            "{out}"
        );
        assert!(out.contains("nullable: Versions::since(5)"), "{out}");
        assert!(out.contains("default: DefaultVal::Null"), "{out}");
        assert!(
            out.contains("pub static FIND_COORDINATOR_REQUEST__COORD: StructSchema"),
            "{out}"
        );
        assert!(
            out.contains("tag: Some(0), tagged: Versions::since(4)"),
            "{out}"
        );
        assert!(out.contains("default: DefaultVal::Int(-1)"), "{out}");
        assert!(out.contains("flexible: Some(Versions::NONE)"), "{out}");
        assert!(
            out.contains("pub static ALL: &[&MessageSchema] = &[&FIND_COORDINATOR_REQUEST];"),
            "{out}"
        );
    }

    #[test]
    fn rejects_tagged_nullable_struct() {
        let s = spec(
            r#"{
          "apiKey": 10, "type": "request", "name": "SomeRequest",
          "validVersions": "0", "flexibleVersions": "0+",
          "fields": [
            { "name": "Opt", "type": "Inner", "versions": "0+", "nullableVersions": "0+",
              "taggedVersions": "0+", "tag": 0, "default": "null",
              "fields": [ { "name": "V", "type": "int32", "versions": "0+" } ] }
          ]
        }"#,
        );
        let err = emit(&[s]).unwrap_err().to_string();
        assert!(
            err.contains("tagged nullable struct fields are not supported"),
            "{err}"
        );
    }

    #[test]
    fn common_structs_and_bool_and_string_defaults() {
        let s = spec(
            r#"{
          "type": "data", "name": "SomeData", "validVersions": "0", "flexibleVersions": "none",
          "fields": [
            { "name": "Flag", "type": "bool", "versions": "0+", "default": "true" },
            { "name": "Label", "type": "string", "versions": "0+", "default": "x" },
            { "name": "Shared", "type": "Common", "versions": "0+" }
          ],
          "commonStructs": [ { "name": "Common", "versions": "0+", "fields": [
            { "name": "V", "type": "int64", "versions": "0+" } ] } ]
        }"#,
        );
        let out = emit(&[s]).unwrap();
        assert!(out.contains("api_key: None, kind: Kind::Data, valid: Versions::range(0, 0), flexible: Versions::NONE"), "{out}");
        assert!(out.contains("default: DefaultVal::Bool(true)"), "{out}");
        assert!(out.contains(r#"default: DefaultVal::Str("x")"#), "{out}");
        assert!(
            out.contains("ty: FieldType::Struct(&SOME_DATA__COMMON)"),
            "{out}"
        );
        assert!(
            out.contains("pub static SOME_DATA__COMMON: StructSchema"),
            "{out}"
        );
    }
}
